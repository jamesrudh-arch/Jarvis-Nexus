# ━━ TOC machinery ━━
class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            self.notify('TOCEntry', (level, text, self.page, key))

from reportlab.platypus.tableofcontents import TableOfContents  # noqa: E402

def heading(text, level=0):
    style = S['h1'] if level == 0 else S['h2']
    key = f'h_{hashlib.md5(text.encode()).hexdigest()[:8]}'
    p = Paragraph(f'<a name="{key}"/><b>{text}</b>', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p

def body(text):
    return Paragraph(text, S['body'])

def code(text):
    return Paragraph(text.replace('\n', '<br/>'), S['mono'])

def caption(text):
    return Paragraph(text, S['caption'])

def mk_table(headers, rows, widths_frac, align_center_cols=()):
    avail = A4[0] - 2 * 0.9 * inch
    widths = [avail * f for f in widths_frac]
    data = [[Paragraph(f'<b>{h}</b>', S['cellhdr']) for h in headers]]
    for r in rows:
        row = []
        for i, c in enumerate(r):
            st = S['cellc'] if i in align_center_cols else S['cell']
            row.append(Paragraph(c, st))
        data.append(row)
    t = Table(data, colWidths=widths, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
    ]
    for i in range(1, len(data)):
        style.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_ODD if i % 2 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    return t

