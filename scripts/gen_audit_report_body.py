# ── TOC machinery ───────────────────────────────────────────────────────────
class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            self.notify("TOCEntry", (getattr(flowable, "bookmark_level", 0),
                                     getattr(flowable, "bookmark_text", ""),
                                     self.page,
                                     getattr(flowable, "bookmark_key", "")))

def add_heading(text, style, level=0):
    key = "h_" + hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph(f'<a name="{key}"/><b>{text}</b>', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p

H1_ORPHAN = (PAGE_H - 2 * MARGIN) * 0.18

def section(title):
    return [CondPageBreak(H1_ORPHAN), add_heading(title, h1, 0)]

def table_of(rows, ratios, header=True, align_center_cols=None):
    widths = [r * AVAIL for r in ratios]
    data = []
    for i, row in enumerate(rows):
        out = []
        for j, c in enumerate(row):
            if i == 0 and header:
                out.append(Paragraph(f"<b>{c}</b>", cell_h))
            else:
                st = cell_c if (align_center_cols and j in align_center_cols) else cell
                out.append(Paragraph(str(c), st))
        data.append(out)
    t = Table(data, colWidths=widths, hAlign="CENTER", repeatRows=1 if header else 0)
    style = [
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    if header:
        style.append(("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL))
        for i in range(1, len(rows)):
            style.append(("BACKGROUND", (0, i), (-1, i),
                          TABLE_STRIPE if i % 2 == 0 else colors.white))
    t.setStyle(TableStyle(style))
    return t

def callout(text, color=ACCENT):
    t = Table([[Paragraph(text, ParagraphStyle("CalloutP", parent=body, spaceAfter=0,
                                               alignment=TA_LEFT))]],
              colWidths=[AVAIL * 0.96], hAlign="CENTER")
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
        ("LINEBEFORE", (0, 0), (0, -1), 3, color),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
    ]))
    return t

